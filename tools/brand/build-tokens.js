#!/usr/bin/env node
/* ============================================================================
   Vakil Saab Agra — token exports.

     node tools/brand/build-tokens.js

   Writes the palette and type stack out in the four shapes somebody is
   actually going to need: JSON for a design tool, CSS custom properties for a
   web page, a Tailwind fragment, and SCSS. All four are generated from
   tools/brand/tokens.js, so they cannot disagree with each other.

   These are *exports for other people*. The site's own tokens live in
   css/styles.css and tailwind.config.js and are not read from here — a build
   step that could repaint the live site from the brand kit is a sharper tool
   than this project needs.
   ========================================================================= */

const fs = require('fs');
const path = require('path');
const { color: C, brand: B, type: T } = require('./tokens');

const ROOT = path.resolve(__dirname, '../..');
const OUT = path.join(ROOT, 'assets/brand/tokens');
fs.mkdirSync(OUT, { recursive: true });

/* The role each colour plays, carried into every export so a swatch is never
   handed over as a bare hex with no instructions. */
const ROLES = {
  ink:    'Primary brand navy. Headings, navigation, primary surfaces.',
  ink2:   'Lighter navy. Top of the navy gradient only.',
  ink3:   'Near-black navy. Bottom of the navy gradient only.',
  gold:   'Accessible gold. The only gold allowed as text on a light background.',
  gold2:  'Decorative gold. Rules, borders, gold on navy. Not body text on paper.',
  gold3:  'Highlight gold. The shine in the metal gradient.',
  gold4:  'Shadow gold. The dark edge of the metal gradient.',
  paper:  'White. Page background.',
  paper2: 'Warm off-white. Alternating section bands.',
  paper3: 'Deeper warm band.',
  line:   'Hairline borders and dividers on paper.',
  muted:  'Secondary text on paper.',
  muted2: 'Tertiary text on paper.',
  slate:  'Body text on navy.',
};

const kebab = (k) => k.replace(/(\d)$/, '-$1');

/* ------------------------------------------------------------------- JSON */

fs.writeFileSync(path.join(OUT, 'brand.json'), JSON.stringify({
  name: B.name,
  domain: B.domain,
  color: Object.fromEntries(Object.entries(C).map(([k, v]) => [k, { value: v, role: ROLES[k] }])),
  font: {
    display: { family: 'Playfair Display', weights: [600, 700, 800, 900], stack: T.display },
    sans:    { family: 'Inter', weights: [400, 500, 600, 700, 800], stack: T.sans },
    devanagari: { family: 'Noto Sans Devanagari', weights: [400, 600, 700], note: 'Fallback for Hindi codepoints in both stacks.' },
  },
  gradient: {
    navy: `linear-gradient(135deg, ${C.ink2} 0%, ${C.ink} 52%, ${C.ink3} 100%)`,
    gold: `linear-gradient(160deg, ${C.gold3} 0%, ${C.gold2} 35%, #c39c40 70%, ${C.gold4} 100%)`,
  },
}, null, 2) + '\n');

/* -------------------------------------------------------------------- CSS */

fs.writeFileSync(path.join(OUT, 'brand.css'),
`/* ${B.name} — brand tokens as CSS custom properties.
   Generated by tools/brand/build-tokens.js. Do not edit by hand. */

:root {
${Object.entries(C).map(([k, v]) => `  --vs-${kebab(k)}: ${v};${' '.repeat(Math.max(1, 10 - k.length))}/* ${ROLES[k]} */`).join('\n')}

  --vs-font-display: ${T.display};
  --vs-font-sans: ${T.sans};

  --vs-gradient-navy: linear-gradient(135deg, var(--vs-ink-2) 0%, var(--vs-ink) 52%, var(--vs-ink-3) 100%);
  --vs-gradient-gold: linear-gradient(160deg, var(--vs-gold-3) 0%, var(--vs-gold-2) 35%, #c39c40 70%, var(--vs-gold-4) 100%);
}
`);

/* ------------------------------------------------------------------- SCSS */

fs.writeFileSync(path.join(OUT, '_brand.scss'),
`// ${B.name} — brand tokens.
// Generated by tools/brand/build-tokens.js. Do not edit by hand.

${Object.entries(C).map(([k, v]) => `$vs-${kebab(k)}: ${v};${' '.repeat(Math.max(1, 10 - k.length))}// ${ROLES[k]}`).join('\n')}

$vs-font-display: ${T.display};
$vs-font-sans: ${T.sans};
`);

/* --------------------------------------------------------------- Tailwind */

fs.writeFileSync(path.join(OUT, 'tailwind.brand.js'),
`/* ${B.name} — Tailwind theme fragment.
   Generated by tools/brand/build-tokens.js. Do not edit by hand.

   Spread this into theme.extend:
     const brand = require('./tailwind.brand');
     module.exports = { theme: { extend: { ...brand } } };
*/

module.exports = {
  colors: {
    ink:   { DEFAULT: '${C.ink}', 2: '${C.ink2}', 3: '${C.ink3}' },
    gold:  { DEFAULT: '${C.gold}', 2: '${C.gold2}', 3: '${C.gold3}', 4: '${C.gold4}' },
    paper: { DEFAULT: '${C.paper}', 2: '${C.paper2}', 3: '${C.paper3}' },
  },
  fontFamily: {
    sans: [${T.sans.split(',').map((s) => JSON.stringify(s.trim().replace(/^'|'$/g, ''))).join(', ')}],
    display: [${T.display.split(',').map((s) => JSON.stringify(s.trim().replace(/^'|'$/g, ''))).join(', ')}],
  },
};
`);

console.log('assets/brand/tokens/ — brand.json, brand.css, _brand.scss, tailwind.brand.js');
