/* ------------------------------------------------------- bilingual output */
/**
 * A microsite is pre-rendered, so its Hindi cannot be fetched later — both
 * languages go into the HTML and CSS shows one. English stays visible with
 * JavaScript off, and Googlebot reads the full English bio in the source.
 *
 * When there is no Hindi for a field, the English is emitted plain, with no
 * class at all: never an empty block, and never a bare key.
 */
function bi(enHtml, hiHtml, tag) {
  const t = tag || 'span';
  if (!hiHtml || String(hiHtml).trim() === '' || hiHtml === enHtml) return enHtml;
  return `<${t} class="i18n-en">${enHtml}</${t}>` +
         `<${t} class="i18n-hi" lang="hi">${hiHtml}</${t}>`;
}

