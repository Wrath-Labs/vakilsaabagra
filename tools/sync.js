/* --------------------------------------------------------------- 6. i18n */
/**
 * data/i18n/hi.json is the file a human edits. This turns it into a script,
 * because js/i18n.js has to have the strings in hand before anything paints
 * and a fetch() would land too late (and not at all over file://).
 *
 * Only Hindi is shipped. English is already in the markup — js/i18n.js reads
 * it out of the DOM and keeps it, so there is nothing to download twice.
 */
const I18N_DIR = path.join(ROOT, 'data', 'i18n');
const HI_JSON = path.join(I18N_DIR, 'hi.json');
const EN_JSON = path.join(I18N_DIR, 'en.json');
let hiCount = 0;
let hiMissing = 0;

if (fs.existsSync(HI_JSON)) {
  const hi = JSON.parse(fs.readFileSync(HI_JSON, 'utf8'));
  /* drop empty values rather than shipping them: js/i18n.js treats a missing
     key as "fall back to English", and an empty string would blank the node */
  const out = {};
  Object.keys(hi).sort().forEach((k) => {
    if (typeof hi[k] === 'string' && hi[k].trim()) out[k] = hi[k].trim();
  });
  hiCount = Object.keys(out).length;

  if (fs.existsSync(EN_JSON)) {
    const en = JSON.parse(fs.readFileSync(EN_JSON, 'utf8'));
    hiMissing = Object.keys(en).filter((k) => !out[k]).length;
    const stray = Object.keys(out).filter((k) => !(k in en) && k.indexOf('js.') !== 0);
    if (stray.length) {
      console.warn(`  ! data/i18n/hi.json has ${stray.length} key(s) with no English counterpart:`);
      stray.slice(0, 10).forEach((k) => console.warn(`      ${k}`));
    }
  }

  fs.writeFileSync(path.join(I18N_DIR, 'hi.js'),
    '/* AUTO-GENERATED by tools/sync.js — do not edit. Source: data/i18n/hi.json */\n' +
    'window.__VS_I18N_HI__ = ' + JSON.stringify(out) + ';\n');
}

